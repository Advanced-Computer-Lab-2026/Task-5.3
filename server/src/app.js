import express from 'express';
import morgan from 'morgan';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import authRoutes from './routes/auth.js';
import itemRoutes from './routes/items.js';
import userRoutes from './routes/users.js';
import settingRoutes from './routes/settings.js';
import { csrfTokenHandler, doubleCsrfProtection } from './middleware/csrf.js';

const app = express();

app.use(morgan('dev'));
app.use(cors({ origin: 'http://localhost:5175', credentials: true }));
app.use(express.json());
app.use(express.urlencoded({ extended: true }));
app.use(cookieParser());

app.get('/api/health', (req, res) => res.json({ ok: true }));

// Issue an anti-CSRF token (a GET, so it is not CSRF-protected itself).
app.get('/api/csrf-token', csrfTokenHandler);

// Auth routes come BEFORE the CSRF check: login/register run before a session exists.
app.use('/api/auth', authRoutes);

// Everything below needs a valid CSRF token on POST/PUT/PATCH/DELETE.
// GET/HEAD/OPTIONS are exempt. A bad or missing token returns 403.
app.use(doubleCsrfProtection);

app.use('/api/items', itemRoutes);
app.use('/api/users', userRoutes);
app.use('/api/settings', settingRoutes);

// Not found
app.use((req, res) => {
  res.status(404).json({ message: 'Not Found' });
});

// Error handler
app.use((err, req, res, next) => {
  console.error(err);
  res.status(err.status || 500).json({ message: err.message || 'Server Error' });
});

export default app;